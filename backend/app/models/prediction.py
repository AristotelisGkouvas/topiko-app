"""What the village thinks will happen.

No money and no accounts. Readers have no login here, so a vote is tied to a
token the browser generates and keeps — enough to stop somebody voting twice by
accident, not enough to stop somebody determined. That is the right amount of
effort for a feature whose prize is an argument in the coffee shop.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from sqlalchemy import ForeignKey, Index, String, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, TimestampMixin, str_enum
from app.models.enums import PredictionChoice

if TYPE_CHECKING:
    from app.models.match import Match


class MatchPrediction(Base, TimestampMixin):
    """One reader's call on one match."""

    __tablename__ = "match_predictions"
    __table_args__ = (
        # One vote per browser per match. Changing your mind updates this row
        # rather than adding a second, which is also why the tally can be a
        # plain count.
        UniqueConstraint("match_id", "voter_token", name="uq_match_predictions"),
        Index("ix_match_predictions_match_choice", "match_id", "choice"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    match_id: Mapped[int] = mapped_column(
        ForeignKey("matches.id", ondelete="CASCADE"), nullable=False, index=True
    )
    #: Opaque, generated by the browser and stored there. Deliberately not an
    #: IP address: a village shares a handful of them, and two neighbours on
    #: the same connection are two opinions.
    voter_token: Mapped[str] = mapped_column(String(64), nullable=False)
    choice: Mapped[PredictionChoice] = mapped_column(
        str_enum(PredictionChoice, 8), nullable=False
    )

    match: Mapped[Match] = relationship()

    def __repr__(self) -> str:
        return f"<MatchPrediction match={self.match_id} {self.choice}>"
